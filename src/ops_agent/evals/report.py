def results_json(res: EvalResults) -> dict[str, Any]:
    def rec(r: CaseRecord) -> dict[str, Any]:
        return {
            "case": r.case.id,
            "kind": r.case.kind,
            "system": r.system,
            "decision": r.decision.model_dump(mode="json") if r.decision else None,
            "answer": r.answer.model_dump(mode="json") if r.answer else None,
            "flags": r.flags,
            "blocked": r.blocked,
            "tools": r.tools_used,
            "proposals": [{k: p[k] for k in ("action", "payload", "status")} for p in r.proposals],
            "raw_unsupported": r.raw_unsupported,
            "final_unsupported": r.final_unsupported,
            "latency_ms": round(r.latency_ms, 2),
            "input_tokens": r.input_tokens,
            "output_tokens": r.output_tokens,
        }

    return {
        "provider": res.provider,
        "started_at": res.started_at,
        "environment": res.environment,
        "unapproved_writes": res.unapproved_writes,
        "metrics": res.metrics,
        "population": res.population,
        "redteam_attempts": res.redteam_attempts,
        "cases": [c.to_json() for c in res.cases],
        "records": [rec(r) for r in (*res.agent, *res.baseline, *res.redteam)],
    }


def check_gate(res: EvalResults, thresholds_path: Path) -> list[str]:
    spec: dict[str, Any] = json.loads(thresholds_path.read_text())
    problems = []
    for key, rule in spec.items():
        if key.startswith("_"):
            continue
        if key == "unapproved_writes":
            value: Any = res.unapproved_writes
        else:
            system, metric = key.split(".", 1)
            value = res.metrics[system][metric]
        if value is None:
            problems.append(f"{key}: no value")
        elif "min" in rule and value < rule["min"]:
            problems.append(f"{key} = {value} < min {rule['min']}")
        elif "max" in rule and value > rule["max"]:
            problems.append(f"{key} = {value} > max {rule['max']}")
    return problems
