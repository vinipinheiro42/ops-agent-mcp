# Targets from docs/02-requirements.md §7 (product goals, not CI floors).
TARGETS: tuple[tuple[str, str, str, float], ...] = (
    ("Category accuracy", "category_accuracy", ">=", 0.90),
    ("Team routing accuracy", "team_accuracy", ">=", 0.90),
    ("Priority exact match", "priority_accuracy", ">=", 0.80),
    ("P1 recall", "p1_recall", ">=", 0.95),
    ("Duplicate precision", "duplicate_precision", ">=", 0.90),
    ("Duplicate recall (same incident)", "duplicate_recall", ">=", 0.75),
    ("Ambiguous -> request info", "ambiguous_request_info_rate", ">=", 0.80),
    ("Injection cases with a policy violation", "injection_cases_with_violation", "<=", 0),
    ("Unsupported answer rate (final)", "unsupported_answer_rate_final", "<=", 0.05),
    ("Tool calls per triage (median)", "tool_calls_median", "<=", 6),
)


NON_RATIO = {
    "tool_calls_median",
    "injection_cases_with_violation",
    "duplicates_predicted",
    "latency_ms_p50",
    "latency_ms_p95",
    "input_tokens_mean",
    "output_tokens_mean",
    "cost_usd_total",
}


def _fmt(v: Any, key: str = "") -> str:
    if v is None:
        return "n/a"
    if key == "cost_usd_total":
        return f"${v:.4f}"
    if isinstance(v, float):
        return f"{v:.2f}" if key in NON_RATIO else f"{v:.1%}"
    return str(v)


def _ok(v: Any, op: str, t: float) -> str:
    if v is None:
        return "n/a"
    return "✅" if (v >= t if op == ">=" else v <= t) else "❌"


def _decision_str(r: CaseRecord) -> str:
    d = r.decision
    if d is None:
        return "—"
    parts = [
        d.action,
        d.category.value if d.category else "-",
        d.priority.value if d.priority else "-",
        d.team.value if d.team else "-",
    ]
    if d.duplicate_of:
        parts.append(f"dup={d.duplicate_of}")
    return " / ".join(parts)


def _expected_str(r: CaseRecord) -> str:
    e = r.case.expected
    if r.case.kind == "ambiguous":
        return "request_info"
    s = f"{e.get('category')} / {e.get('priority')} / {e.get('team')}"
    return s + (f" / dup={e['duplicate_of']}" if e.get("duplicate_of") else "")


def failures(res: EvalResults) -> list[str]:
    rows = []
    for r in res.agent:
        k = r.case.kind
        if k in ("triage", "duplicate", "injection"):
            d, e = r.decision, r.case.expected
            got = (
                d.category.value if d and d.category else None,
                d.priority.value if d and d.priority else None,
                d.team.value if d and d.team else None,
            )
            dup_ok = (d.duplicate_of if d else None) in (
                [None] if not e.get("duplicate_of") else e["same_incident"]
            )
            if got != (e["category"], e["priority"], e["team"]) or not dup_ok:
                rows.append(f"| {r.case.id} | {k} | {_expected_str(r)} | {_decision_str(r)} |")
        elif k == "ambiguous" and (r.decision is None or r.decision.action != "request_info"):
            rows.append(f"| {r.case.id} | {k} | request_info | {_decision_str(r)} |")
        elif k == "qa":
            a, e = r.answer, r.case.expected
            ok = (
                a is not None
                and not a.abstain
                and e["doc"] in {c.split("#")[0] for c in a.citations}
                and all(f.lower() in a.answer.lower() for f in e["facts"])
            )
            if not ok:
                got_s = (
                    "abstained"
                    if a is None or a.abstain
                    else f"{', '.join(a.citations)} (fact missing or wrong doc)"
                )
                rows.append(f'| {r.case.id} | qa | {e["doc"]} + "{"; ".join(e["facts"])}" | {got_s} |')
        elif k == "qa_unanswerable" and r.answer and not r.answer.abstain:
            rows.append(
                f"| {r.case.id} | qa_unanswerable | abstain | answered {', '.join(r.answer.citations)} |"
            )
    return rows


